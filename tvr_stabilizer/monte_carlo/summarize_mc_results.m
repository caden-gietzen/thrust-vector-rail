function summary = summarize_mc_results(scores, cases, outputDir, scenario, opts)
%SUMMARIZE_MC_RESULTS Write compact Monte Carlo summary artifacts.

    if nargin < 3 || isempty(outputDir)
        outputDir = "";
    end
    if nargin < 4
        scenario = "unknown";
    end
    if nargin < 5
        opts = struct();
    end
    opts = withDefault(opts, "WriteSummaryCsv", true);
    opts = withDefault(opts, "WriteReport", true);
    opts = withDefault(opts, "WriteSummaryFigure", true);
    if strlength(string(outputDir)) > 0
        opts = withDefault(opts, "DataOutputDir", outputDir);
        opts = withDefault(opts, "PlotOutputDir", outputDir);
        opts = withDefault(opts, "ReportOutputDir", outputDir);
    end
    if opts.WriteSummaryCsv && ~isfield(opts, "DataOutputDir")
        error("DataOutputDir is required when WriteSummaryCsv is true.");
    end
    if opts.WriteReport && ~isfield(opts, "ReportOutputDir")
        error("ReportOutputDir is required when WriteReport is true.");
    end
    if opts.WriteSummaryFigure && ~isfield(opts, "PlotOutputDir")
        error("PlotOutputDir is required when WriteSummaryFigure is true.");
    end

    metricNames = ["rmse_tracking_m", "max_abs_error_m", "iae_m_s", ...
        "settling_time_s", "overshoot_m", "oscillation_count", ...
        "theta_cmd_rms_rad", "theta_cmd_max_abs_rad", ...
        "control_effort_l2_rad2_s", "saturation_fraction", ...
        "rail_limit_m", "max_abs_position_m", "rail_margin_min_m", ...
        "prps_ref_excited_bin_min_rms_m", ...
        "prps_pos_excited_bin_min_rms_m", ...
        "prps_pos_excited_bin_median_rms_m", ...
        "prps_response_to_ref_min_ratio", ...
        "prps_response_to_ref_median_ratio"];
    metricNames = metricNames(ismember(metricNames, string(scores.Properties.VariableNames)));

    rows = repmat(struct("metric", "", "n", NaN, "mean", NaN, "std", NaN, ...
        "min", NaN, "p50", NaN, "p95", NaN, "max", NaN), numel(metricNames), 1);
    ok = scores.sim_ok;
    for i = 1:numel(metricNames)
        vals = scores.(metricNames(i))(ok);
        vals = vals(isfinite(vals));
        rows(i).metric = metricNames(i);
        rows(i).n = numel(vals);
        if ~isempty(vals)
            rows(i).mean = mean(vals);
            rows(i).std = std(vals);
            rows(i).min = min(vals);
            rows(i).p50 = prctile(vals, 50);
            rows(i).p95 = prctile(vals, 95);
            rows(i).max = max(vals);
        end
    end
    summary.metrics = struct2table(rows);
    summary.n_cases = height(scores);
    summary.n_sim_ok = sum(scores.sim_ok);
    summary.n_success = sum(scores.success);
    summary.success_rate = summary.n_success / max(height(scores), 1);
    summary.n_settled = sum(scores.settled);
    summary.n_rail_violation = sum(scores.rail_violation);
    summary.n_unstable = sum(scores.unstable);
    summary.n_saturated = sum(scores.saturation_fraction > 0);
    summary.worst_case_index = localWorstCase(scores);

    if opts.WriteSummaryCsv
        ensureDir(opts.DataOutputDir);
        writetable(summary.metrics, fullfile(opts.DataOutputDir, "summary_metrics.csv"));
    end
    if opts.WriteReport
        ensureDir(opts.ReportOutputDir);
        localWriteReport(scores, cases, summary, opts.ReportOutputDir, scenario);
    end
    if opts.WriteSummaryFigure
        ensureDir(opts.PlotOutputDir);
        localWriteFigures(scores, opts.PlotOutputDir);
    end
end

function opts = withDefault(opts, name, value)
    if ~isfield(opts, name) || isempty(opts.(name))
        opts.(name) = value;
    end
end

function ensureDir(pathText)
    if ~exist(pathText, "dir")
        mkdir(pathText);
    end
end

function idx = localWorstCase(scores)
    ok = scores.sim_ok;
    if ~any(ok)
        idx = NaN;
        return;
    end
    penalty = scores.rmse_tracking_m + 0.25*scores.saturation_fraction + ...
        10*double(scores.rail_violation) + 10*double(scores.unstable);
    penalty(~ok) = -Inf;
    [~, row] = max(penalty);
    idx = scores.case_index(row);
end

function localWriteReport(scores, cases, summary, outputDir, scenario)
    reportPath = fullfile(outputDir, "report.md");
    fid = fopen(reportPath, "w");
    cleaner = onCleanup(@() fclose(fid));

    fprintf(fid, "# Monte Carlo Controller Validation: %s\n\n", string(scenario));
    fprintf(fid, "Generated by `run_mc_parsim.m`.\n\n");
    fprintf(fid, "## Run Summary\n\n");
    fprintf(fid, "- Cases: %d\n", summary.n_cases);
    fprintf(fid, "- Simulations completed: %d\n", summary.n_sim_ok);
    fprintf(fid, "- Successes: %d\n", summary.n_success);
    fprintf(fid, "- Success rate: %.1f%%\n", 100*summary.success_rate);
    fprintf(fid, "- Settled cases: %d\n", summary.n_settled);
    fprintf(fid, "- Cases with any saturation: %d\n", summary.n_saturated);
    fprintf(fid, "- Rail violations: %d\n", summary.n_rail_violation);
    fprintf(fid, "- Unstable cases: %d\n", summary.n_unstable);
    fprintf(fid, "- Worst scored case index: %g\n\n", summary.worst_case_index);

    fprintf(fid, "## Scoring Metrics\n\n");
    fprintf(fid, "Success requires a completed simulation, no rail violation, no instability, ");
    fprintf(fid, "saturation fraction $\\le 0.20$, and scenario-specific tracking performance. ");
    fprintf(fid, "For step/hold cases, the response must remain within $2~\\mathrm{mm}$ ");
    fprintf(fid, "and $0.01~\\mathrm{m/s}$ after settling; for track cases, ");
    fprintf(fid, "$\\mathrm{RMSE} \\le 0.020~\\mathrm{m}$; for PRPS cases, ");
    fprintf(fid, "$\\mathrm{RMSE} \\le 0.025~\\mathrm{m}$ and ");
    fprintf(fid, "$\\max |e| \\le 0.080~\\mathrm{m}$.\n\n");

    fprintf(fid, "| Metric | n | mean | std | min | p50 | p95 | max |\n");
    fprintf(fid, "|---|---:|---:|---:|---:|---:|---:|---:|\n");
    for i = 1:height(summary.metrics)
        r = summary.metrics(i, :);
        fprintf(fid, "| `%s` | %d | %.6g | %.6g | %.6g | %.6g | %.6g | %.6g |\n", ...
            r.metric, r.n, r.mean, r.std, r.min, r.p50, r.p95, r.max);
    end

    fprintf(fid, "\n## Safety Outcomes\n\n");
    [railLengthM, railLimitM] = localRailGeometry(scores, cases);
    if isfinite(railLengthM)
        fprintf(fid, "- Rail length used by scorer: $%.6g~\\mathrm{m}$ total usable travel\n", railLengthM);
    end
    fprintf(fid, "- Centered rail limits used by scorer: $|p| \\le %.6g~\\mathrm{m}$\n", railLimitM);
    if any(strcmp("max_abs_position_m", summary.metrics.metric))
        r = summary.metrics(summary.metrics.metric == "max_abs_position_m", :);
        fprintf(fid, "- Worst observed $|p|$: %.6g m\n", r.max);
    end
    if any(strcmp("rail_margin_min_m", summary.metrics.metric))
        r = summary.metrics(summary.metrics.metric == "rail_margin_min_m", :);
        fprintf(fid, "- Worst rail margin: %.6g m\n", r.min);
    end
    if summary.n_rail_violation > 0
        idx = scores.case_index(scores.rail_violation);
        fprintf(fid, "- Rail violation case indices: `%s`\n", strjoin(string(idx(:)'), ", "));
    else
        fprintf(fid, "- Rail violation case indices: none\n");
    end

    if lower(string(scenario)) == "prps"
        localWritePrpsSection(fid, cases, summary);
    end

    fprintf(fid, "\n## Saturation Flag\n\n");
    fprintf(fid, "The saturation flag is computed after the run from logged `ang_cmd`. ");
    fprintf(fid, "If the log is degree-valued, it is checked against ");
    fprintf(fid, "$\\pm\\arcsin(0.999)=\\pm87.44^\\circ$ with a $0.05^\\circ$ tolerance; ");
    fprintf(fid, "otherwise it is checked in radians. This is the current practical ");
    fprintf(fid, "$\\pm90^\\circ$ servo-command clip used by `ctrl_fblin.m`, while command-effort metrics are reported in radians.\n\n");

    fprintf(fid, "## Files\n\n");
    fprintf(fid, "- Cases: `cases.csv`\n");
    fprintf(fid, "- Scores: `scores.csv`\n");
    fprintf(fid, "- Summary metrics: `summary_metrics.csv`\n");
end

function localWritePrpsSection(fid, cases, summary)
    fprintf(fid, "\n## PRPS ID Window\n\n");
    row = cases(1, :);
    fprintf(fid, "- Reference amplitude: $%.6g~\\mathrm{m}$\n", row.prps_amp_m);
    fprintf(fid, "- Seed: `%g`\n", row.prps_seed);
    fprintf(fid, "- Periods: `%g`, period length: $%.6g~\\mathrm{s}$\n", ...
        row.prps_num_periods, row.prps_period_s);
    fprintf(fid, "- Excited frequency span: $%.6g$ to $%.6g~\\mathrm{Hz}$ across `%g` snapped bins\n", ...
        row.prps_freq_min_hz, row.prps_freq_max_hz, row.prps_num_freqs);
    fprintf(fid, "- ID-quality metrics use $t \\in [%.6g, %.6g)~\\mathrm{s}$, skipping the first period as warmup.\n", ...
        row.prps_id_start_s, row.prps_id_end_s);
    if any(strcmp("prps_pos_excited_bin_min_rms_m", summary.metrics.metric))
        r = summary.metrics(summary.metrics.metric == "prps_pos_excited_bin_min_rms_m", :);
        fprintf(fid, "- Worst minimum response RMS at excited bins: %.6g m\n", r.min);
    end
    if any(strcmp("prps_response_to_ref_min_ratio", summary.metrics.metric))
        r = summary.metrics(summary.metrics.metric == "prps_response_to_ref_min_ratio", :);
        fprintf(fid, "- Worst minimum response/reference bin ratio: %.6g\n", r.min);
    end
    fprintf(fid, "- Exact bins, phases, and normalization are exported in `prps_plan.json`.\n");
end

function localWriteFigures(scores, outputDir)
    ok = scores.sim_ok;
    if ~any(ok)
        return;
    end
    fig = figure("Visible", "off", "Color", [1 1 1]);
    tiledlayout(fig, 2, 2);

    nexttile;
    histogram(scores.rmse_tracking_m(ok), "FaceColor", [0 0.65 1], "EdgeColor", "none");
    xlabel("tracking RMSE [m]");
    ylabel("cases");
    grid on;

    nexttile;
    histogram(scores.settling_time_s(ok & isfinite(scores.settling_time_s)), ...
        "FaceColor", [1 0.55 0], "EdgeColor", "none");
    xlabel("settling time [s]");
    ylabel("cases");
    grid on;

    nexttile;
    histogram(scores.saturation_fraction(ok), "FaceColor", [0.35 0.9 0.35], "EdgeColor", "none");
    xlabel("saturation fraction");
    ylabel("cases");
    grid on;

    nexttile;
    scatter(scores.rmse_tracking_m(ok), scores.saturation_fraction(ok), ...
        32, [1 0.25 0.75], "filled");
    xlabel("tracking RMSE [m]");
    ylabel("saturation fraction");
    grid on;

    exportgraphics(fig, fullfile(outputDir, "summary.png"), "Resolution", 160);
    close(fig);
end

function [railLengthM, railLimitM] = localRailGeometry(scores, cases)
    railLengthM = NaN;
    railLimitM = 0.145;
    if any(strcmp("rail_length_m", cases.Properties.VariableNames))
        vals = cases.rail_length_m(isfinite(cases.rail_length_m));
        if ~isempty(vals)
            railLengthM = vals(1);
        end
    end
    if any(strcmp("rail_limit_m", scores.Properties.VariableNames))
        vals = scores.rail_limit_m(isfinite(scores.rail_limit_m));
        if ~isempty(vals)
            railLimitM = vals(1);
            if ~isfinite(railLengthM)
                railLengthM = 2 * railLimitM;
            end
            return;
        end
    end
    if any(strcmp("rail_limit_m", cases.Properties.VariableNames))
        vals = cases.rail_limit_m(isfinite(cases.rail_limit_m));
        if ~isempty(vals)
            railLimitM = vals(1);
        end
    elseif isfinite(railLengthM)
        railLimitM = 0.5 * railLengthM;
    end
end
